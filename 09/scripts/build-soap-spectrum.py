"""Regenerate the compact D65/CIE spectral integration weights."""
import csv
import hashlib
import io
from pathlib import Path
import urllib.request

SOURCES = {
    'CIE_xyz_1931_2deg.csv': 'fa663e3535a7e0763a745993a1f0a192eb0275ac46ad2d1befd7626841e713c1',
    'CIE_std_illum_D65.csv': 'e76f210bffff3d552ef7113025da5f325d5dfec200dd4b878b1a2f3a507032cb',
}

def read(name):
    data = urllib.request.urlopen('https://files.cie.co.at/Publications-datasets/' + name).read()
    assert hashlib.sha256(data).hexdigest() == SOURCES[name], 'CIE source checksum changed'
    return {int(row[0]): list(map(float, row[1:])) for row in csv.reader(io.StringIO(data.decode()))}

xyz, d65 = map(read, SOURCES)
matrix = [[3.2404542, -1.5371385, -.4985314], [-.969266, 1.8760108, .041556], [.0556434, -.2040259, 1.0572252]]
weights = []
for wavelength in range(360, 831, 5):
    weights.append([wavelength, *[sum(a*b for a,b in zip(row, xyz[wavelength])) * d65[wavelength][0] for row in matrix]])
white = [sum(row[i+1] for row in weights) for i in range(3)]
header = '''// Generated by scripts/build-soap-spectrum.py. Wavelengths in nm, then RGB weights.
// Derived from CIE 2019 CIE 1931 2-degree observer and standard illuminant D65:
// https://doi.org/10.25039/CIE.DS.xvudnb9b and https://doi.org/10.25039/CIE.DS.hjfjmt59
// Data and derived weights: CC BY-SA 4.0, International Commission on Illumination.
// https://creativecommons.org/licenses/by-sa/4.0/
// Changes: sampled every 5 nm, D65-weighted, converted to linear sRGB, normalized to white.
export const SOAP_SPECTRUM = [
'''
rows = ['  [' + ','.join([str(row[0])] + [format(row[i+1]/white[i], '.10g') for i in range(3)]) + '],' for row in weights]
Path(__file__).resolve().parents[1].joinpath('soap-spectrum.js').write_text(header + '\n'.join(rows) + '\n];\n')
